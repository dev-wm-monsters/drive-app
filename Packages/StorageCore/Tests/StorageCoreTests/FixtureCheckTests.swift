import FixtureCheckKit
import Foundation
import StorageCore
import XCTest

final class FixtureCheckTests: XCTestCase {
    private var tempDirs: [URL] = []

    override func tearDown() {
        for dir in tempDirs { try? FileManager.default.removeItem(at: dir) }
        tempDirs.removeAll()
        super.tearDown()
    }

    private func makeTempDir() -> URL {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("fixture-check-\(UUID().uuidString)")
        tempDirs.append(dir)
        return dir
    }

    /// Small catalog for the negative cases so they stay fast in debug builds.
    private let small = FixtureCatalog(name: "small", revision: "r1", layout: [
        .file("a.bin", 5000),
        .file("z.bin", 1),
        .directory("d", [.file("b.bin", 300)]),
    ])

    private func failing(_ report: VerifyReport) -> [String] {
        report.checks.filter { !$0.pass }.map(\.name)
    }

    func testGenerateThenVerifySpikePasses() throws {
        let dir = makeTempDir()
        XCTAssertEqual(try FixtureGenerator.generate(.spike, into: dir), 8)
        let report = FixtureVerifier.verify(.spike, root: dir, randomReads: 100, seed: 42)
        XCTAssertTrue(report.pass, "failing: \(failing(report))")
        let names = Set(report.checks.map(\.name))
        for entry in FixtureCatalog.spike.entries where entry.fixture != nil {
            XCTAssertTrue(names.contains("sha256:" + entry.path))
            XCTAssertTrue(names.contains("size:" + entry.path))
            XCTAssertTrue(names.contains("ranges:" + entry.path))
        }
        XCTAssertTrue(names.isSuperset(of: ["root", "tree:/", "tree:/nested", "random-reads", "zero-length-read"]))
        // Generated bytes equal the manifest hashes.
        let manifest = FixtureManifest.make(.spike)
        for file in manifest.files {
            XCTAssertEqual(try FixtureVerifier.sha256(of: dir.appendingPathComponent(file.path)), file.sha256, file.path)
        }
    }

    func testVerifyFailsWhenOneByteFlipped() throws {
        let dir = makeTempDir()
        _ = try FixtureGenerator.generate(.spike, into: dir)
        let target = dir.appendingPathComponent("seg.bin")
        let handle = try FileHandle(forUpdating: target)
        let offset = Limits.segmentSize - 1
        try handle.seek(toOffset: offset)
        let original = try XCTUnwrap(handle.read(upToCount: 1))
        try handle.seek(toOffset: offset)
        try handle.write(contentsOf: Data([original[original.startIndex] ^ 0x01]))
        try handle.close()

        let report = FixtureVerifier.verify(.spike, root: dir, randomReads: 0, seed: 1)
        XCTAssertFalse(report.pass)
        let failed = failing(report)
        XCTAssertTrue(failed.contains("sha256:seg.bin"), "\(failed)")
        XCTAssertTrue(failed.contains("ranges:seg.bin"), "boundary read at 4 MiB-1 catches it: \(failed)")
        XCTAssertTrue(report.checks.contains { $0.name == "size:seg.bin" && $0.pass }, "size is unchanged")
        XCTAssertEqual(Set(failed), ["sha256:seg.bin", "ranges:seg.bin"])
    }

    func testVerifyDetectsMissingExtraTruncatedAndWrongKind() throws {
        let dir = makeTempDir()
        _ = try FixtureGenerator.generate(small, into: dir)
        XCTAssertTrue(FixtureVerifier.verify(small, root: dir, randomReads: 50, seed: 7).pass)

        let fm = FileManager.default
        try fm.removeItem(at: dir.appendingPathComponent("z.bin"))
        try Data("x".utf8).write(to: dir.appendingPathComponent("extra.txt"))
        let handle = try FileHandle(forWritingTo: dir.appendingPathComponent("a.bin"))
        try handle.truncate(atOffset: 4999)
        try handle.close()
        try fm.removeItem(at: dir.appendingPathComponent("d/b.bin"))
        try fm.createDirectory(at: dir.appendingPathComponent("d/b.bin"), withIntermediateDirectories: false)

        let report = FixtureVerifier.verify(small, root: dir, randomReads: 50, seed: 7)
        XCTAssertFalse(report.pass)
        let failed = Set(failing(report))
        XCTAssertTrue(failed.isSuperset(of: ["tree:/", "kind:z.bin", "size:a.bin", "sha256:a.bin", "ranges:a.bin", "kind:d/b.bin"]),
                      "\(failed)")
    }

    func testVerifyMissingRoot() {
        let report = FixtureVerifier.verify(small, root: makeTempDir(), randomReads: 5, seed: 1)
        XCTAssertFalse(report.pass)
        XCTAssertEqual(report.checks.map(\.name), ["root"])
    }

    func testRandomReadsAreSeededAndDetectCorruption() throws {
        let dir = makeTempDir()
        _ = try FixtureGenerator.generate(small, into: dir)
        let a = FixtureVerifier.verify(small, root: dir, randomReads: 30, seed: 99)
        let b = FixtureVerifier.verify(small, root: dir, randomReads: 30, seed: 99)
        XCTAssertEqual(a, b, "same seed, same report")
        // Corrupt every byte of a.bin after the first: random reads must notice.
        let bytes = try Data(contentsOf: dir.appendingPathComponent("a.bin"))
        try Data(bytes.prefix(1) + bytes.dropFirst().map { $0 ^ 0xFF }).write(to: dir.appendingPathComponent("a.bin"))
        let c = FixtureVerifier.verify(small, root: dir, randomReads: 200, seed: 99)
        XCTAssertTrue(c.checks.contains { $0.name == "random-reads" && !$0.pass })
    }

    func testCLI() throws {
        var out: [String] = []
        var err: [String] = []
        func run(_ args: [String], catalog: FixtureCatalog = .spike) -> Int32 {
            FixtureCheckCLI.run(args, catalog: catalog, out: { out.append($0) }, err: { err.append($0) })
        }
        XCTAssertEqual(run([]), 2)
        XCTAssertEqual(run(["bogus"]), 2)
        XCTAssertEqual(run(["verify"]), 2)
        XCTAssertEqual(run(["verify", "/x", "--random-reads"]), 2)
        XCTAssertEqual(run(["verify", "/x", "--random-reads", "-3"]), 2)
        XCTAssertEqual(run(["verify", "/x", "--seed", "abc"]), 2)
        XCTAssertEqual(run(["generate"]), 2)

        out.removeAll()
        XCTAssertEqual(run(["manifest"]), 0)
        let manifest = try JSONDecoder().decode(Manifest.self, from: Data(out.joined().utf8))
        XCTAssertEqual(manifest.catalog, "spike")
        XCTAssertEqual(manifest.directories, ["nested"])
        XCTAssertEqual(manifest.files.count, 8)

        let dir = makeTempDir()
        XCTAssertEqual(run(["generate", dir.path], catalog: small), 0)
        out.removeAll()
        XCTAssertEqual(run(["verify", dir.path, "--random-reads", "10", "--seed", "3"], catalog: small), 0)
        let report = try JSONDecoder().decode(VerifyReport.self, from: Data(out.joined().utf8))
        XCTAssertTrue(report.pass)
        XCTAssertEqual(report.seed, 3)
        XCTAssertEqual(report.randomReads, 10)
        out.removeAll()
        XCTAssertEqual(run(["verify", makeTempDir().path], catalog: small), 1)
        let failed = try JSONDecoder().decode(VerifyReport.self, from: Data(out.joined().utf8))
        XCTAssertFalse(failed.pass)
    }

    /// Golden hashes (cross-checked with coreutils `sha256sum` on generated files). A change
    /// here means the fixture generator changed and every saved fixture-manifest is invalid.
    func testSpikeManifestGolden() {
        let golden: [String: (UInt64, String)] = [
            "64k.bin": (65_536, "3dfc9ba983164973780927e99c98be6ef3994a223fc1afa297d933fe039268d3"),
            "empty.bin": (0, "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"),
            "nested/deep.bin": (100_000, "93236cfdf943093de95c9123405aa309cc4b891539332fcd791933abdb19ad12"),
            "one.bin": (1, "65c74c15a686187bb6bbf9958f494fc6b80068034a659a9ad44991b08c58f2d2"),
            "seg-minus-1.bin": (4_194_303, "dcea34ca859660f226022a8ccd5c3d2804e03a277043d9e7dad106e55c43e20b"),
            "seg-plus-1.bin": (4_194_305, "9f8c6158243bcc1eac867c9493cf768f9e1f814173bb5b27ccfc21c2ecc56aad"),
            "seg.bin": (4_194_304, "4874749ebbdfc1d71124ca7799b5d411cb0b6e470640cb55741c62f10f3254c5"),
            "\u{00DC}n\u{00EF}c\u{00F8}d\u{00E9} name.bin": (12_345, "912ab2954610d7f5c5fe3028b12bec66baf48083f99af9068bf7eb97c337819c"),
        ]
        let manifest = FixtureManifest.make(.spike)
        XCTAssertEqual(manifest.files.count, golden.count)
        for file in manifest.files {
            guard let (size, hash) = golden[file.path] else { XCTFail("unexpected \(file.path)"); continue }
            XCTAssertEqual(file.size, size, file.path)
            XCTAssertEqual(file.sha256, hash, file.path)
        }
    }
}
