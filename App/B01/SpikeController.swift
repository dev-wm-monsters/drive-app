// SpikeController.swift
// B01 host-app wiring: registers the StorageService LaunchAgent with SMAppService, reports its
// status, proves app ↔ service IPC (status ping + a checksummed byte range) and shows whether the
// FSKit module is installed and enabled.
//
// Docs / headers relied on:
// - https://developer.apple.com/documentation/servicemanagement/smappservice
// - https://developer.apple.com/documentation/servicemanagement/smappservice/agent(plistname:)
//   (plist must be in Contents/Library/LaunchAgents; the name includes ".plist")
// - https://developer.apple.com/documentation/servicemanagement/smappservice/status-swift.enum
// - https://developer.apple.com/documentation/servicemanagement/smappservice/opensystemsettingsloginitems()
// - https://developer.apple.com/documentation/fskit/fsclient and macOS 26.5 SDK FSClient.h /
//   FSModuleIdentity.h (`installedExtensions` async getter, `isEnabled`)
// G0-VERIFY: FSClient.installedExtensions from the sandboxed host app (no FSKit entitlement). If it
// fails, the UI shows the error and the user checks System Settings instead.

import Foundation
@preconcurrency import FSKit
import Observation
import os
import ServiceManagement
import StorageCore

@MainActor
@Observable
final class SpikeController {
    private(set) var serviceStatus = "Unknown"
    private(set) var serviceNeedsApproval = false
    private(set) var pingResult = "Not checked"
    private(set) var sampleResult = "Not read"
    private(set) var extensionStatus = "Not checked"

    /// Shell command the tester pastes into Terminal. mount(8) turns the URL into an
    /// FSGenericURLResource for the module whose FSShortName is `driveappspike`.
    /// G0-VERIFY: mount-point rules for FSKit URL resources (Apple's sample mounts under ~;
    /// macFUSE reports /Volumes only) and whether `-F` needs sudo for a user-owned directory.
    let mountCommand = "mkdir -p ~/DriveAppSpike && mount -F -t driveappspike driveappspike://spike ~/DriveAppSpike"
    let unmountCommand = "umount ~/DriveAppSpike"

    private let client = StorageServiceClient()
    private let identity = ServiceIdentity.resolve()
    private let logger = Logger(subsystem: Bundle.main.bundleIdentifier ?? "DriveApp", category: "b01")

    init() {
        refreshServiceStatus()
    }

    private var agent: SMAppService? {
        guard let identity else { return nil }
        return SMAppService.agent(plistName: identity.serviceBundleID + ".plist")
    }

    // MARK: Service registration

    func refreshServiceStatus() {
        guard let agent else {
            serviceStatus = "Misconfigured: DriveAppBaseBundleID missing from Info.plist"
            return
        }
        let status = agent.status
        serviceNeedsApproval = status == .requiresApproval
        switch status {
        case .notRegistered: serviceStatus = "Not registered"
        case .enabled: serviceStatus = "Enabled"
        case .requiresApproval: serviceStatus = "Needs approval in Login Items"
        case .notFound: serviceStatus = "LaunchAgent plist not found in app bundle"
        @unknown default: serviceStatus = "Unknown status \(status.rawValue)"
        }
        let health = client.health.state
        serviceStatus += " · connection \(health)"
    }

    func registerService() {
        guard let agent else { return refreshServiceStatus() }
        do {
            try agent.register()
            logger.info("StorageService LaunchAgent registered")
        } catch {
            logger.error("SMAppService register failed: \(error.localizedDescription, privacy: .public)")
            serviceStatus = "Register failed: \(error.localizedDescription)"
            return
        }
        refreshServiceStatus()
    }

    func unregisterService() {
        guard let agent else { return refreshServiceStatus() }
        do {
            try agent.unregister()
        } catch {
            serviceStatus = "Unregister failed: \(error.localizedDescription)"
            return
        }
        refreshServiceStatus()
    }

    func openLoginItems() {
        SMAppService.openSystemSettingsLoginItems()
    }

    // MARK: IPC proof

    func ping() async {
        pingResult = "Pinging…"
        do throws(StorageError) {
            let status = try await client.call(.status).expectStatus()
            pingResult = "OK · v\(status.version) · pid \(status.pid) · catalog \(status.catalog)"
        } catch {
            pingResult = "Failed: \(error.description) (errno \(error.posixErrorCode))"
        }
        refreshServiceStatus()
    }

    /// Reads one fixture range over XPC and compares its SHA-256 with the locally generated bytes.
    func readSample() async {
        sampleResult = "Reading…"
        do throws(StorageError) {
            let attributes = try await client.call(.lookup(parent: .root, name: "64k.bin")).expectAttributes()
            let length = min(attributes.size, Limits.maxReadReply)
            let data = try await client.call(.readRange(requestID: client.nextRequestID(),
                                                        item: attributes.id,
                                                        revision: attributes.revision,
                                                        offset: 0,
                                                        length: Int64(length))).expectBytes()
            let received = SHA256Digest.hex(data)
            let expected = FixtureCatalog.spike.fixture(for: attributes.id)
                .map { SHA256Digest.hex($0.data(in: ByteRange(offset: 0, length: length))) }
            let verdict = expected == received ? "matches fixture" : "MISMATCH"
            sampleResult = "\(data.count) bytes · sha256 \(received.prefix(12))… · \(verdict)"
        } catch {
            sampleResult = "Failed: \(error.description) (errno \(error.posixErrorCode))"
        }
        refreshServiceStatus()
    }

    // MARK: FSKit module

    func refreshExtensionStatus() async {
        guard let identity else {
            extensionStatus = "Misconfigured: DriveAppBaseBundleID missing"
            return
        }
        extensionStatus = await Self.extensionState(bundleID: identity.extensionBundleID)
    }

    nonisolated private static func extensionState(bundleID: String) async -> String {
        do {
            let modules = try await FSClient.shared.installedExtensions
            guard let module = modules.first(where: { $0.bundleIdentifier == bundleID }) else {
                return "Not installed (move DriveApp to /Applications and launch it once)"
            }
            return module.isEnabled
                ? "Enabled"
                : "Disabled: System Settings › General › Login Items & Extensions › File System Extensions"
        } catch {
            return "Unknown (\(error.localizedDescription))"
        }
    }
}
